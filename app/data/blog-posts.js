const ids = [
  'business-1', 'business-2', 'business-3',
  'individual-1', 'individual-2', 'individual-3',
  'news-1', 'news-2', 'news-3',
]

export const blogPosts = Object.fromEntries(
  ids.map((id) => [id, { ...basePost, ...cardPreview, id, slug: id }]),
)

export function getBlogPostById(id) {
  return blogPosts[id] || { ...basePost, ...cardPreview, id, slug: id }
}

export function getBlogListPosts() {
  return [
    { prefix: 'business', title: 'Бизнесу' },
    { prefix: 'individual', title: 'Частным лицам' },
    { prefix: 'news', title: 'Новости' },
  ].map(({ prefix, title }) => ({
    title,
    posts: [1, 2, 3].map((index) => {
      const id = `${prefix}-${index}`
      const post = blogPosts[id]

      return {
        id,
        to: `/blog/${id}`,
        image: post.image,
        tags: post.tags,
        date: post.cardDate,
        title: post.cardTitle,
        text: post.excerpt,
      }
    }),
  }))
}
