function entry(original, genitive, dative, accusative, instrumental, prepositional) {
  return {
    original,
    nominative: original,
    genitive,
    dative,
    accusative,
    instrumental,
    prepositional,
  }
}

// муж. род: Казахстан
function masc(base) {
  return entry(base, `${base}а`, `${base}у`, base, `${base}ом`, `${base}е`)
}

// муж. на -й: Китай
function mascY(base) {
  const stem = base.slice(0, -1)
  return entry(base, `${stem}я`, `${stem}ю`, base, `${stem}ем`, `${stem}е`)
}

// муж. на -ец: Кипр → Кипра (special handled manually often)
function mascEc(base) {
  const stem = base.slice(0, -2)
  return entry(base, `${stem}ца`, `${stem}цу`, base, `${stem}цем`, `${stem}це`)
}

// жен. на -ия: Турция, Франция
function femIa(base) {
  const stem = base.slice(0, -2)
  return entry(base, `${stem}ии`, `${stem}ии`, `${stem}ию`, `${stem}ией`, `${stem}ии`)
}

// жен. на -а: Канада
function femA(base) {
  const stem = base.slice(0, -1)
  return entry(base, `${stem}ы`, `${stem}е`, `${stem}у`, `${stem}ой`, `${stem}е`)
}

// жен. на -я (не -ия): Кения covered by femIa; Болгария = femIa
function femYa(base) {
  const stem = base.slice(0, -1)
  return entry(base, `${stem}и`, `${stem}е`, `${stem}ю`, `${stem}ей`, `${stem}е`)
}

// несклоняемые
function ind(base) {
  return entry(base, base, base, base, base, base)
}

